//! Generate a real, drivable reference-ghost fixture set for Layer 6 replay
//! verification (plan.md §Testing Layer 6).
//!
//! # Why this binary exists
//!
//! `reference-ghosts.json` is the regression corpus that `tests/replay.rs`
//! re-simulates every commit to catch physics drift. The file that shipped
//! held 201 *synthetic* ghosts (`synth-track-*` keys) whose `finish_time_ms`
//! values were hand-picked constants, not physics-derived. That defeats the
//! purpose of a drift gate: a hand-picked time cannot drift, so the gate can
//! only ever test that the *shape* still produces *some* finish, never that it
//! produces the *right* finish.
//!
//! Production drawrace is not deployed (no reachable DB), so the "extract
//! >=200 real accepted ghosts from production" framing is impossible as
//! written. The repo does, however, ship two real, drivable, physics-derived
//! ghost sources, and this binary leverages both:
//!
//! 1. **The seed-ghost generator** (`crates/api/src/bin/generate-seed-ghosts*`
//!    + the committed `seeds/track_{1,2,3}/*.blob` pool it emits). These are
//!    the canonical drivable wheel shapes the game ships as its seed pool —
//!    real player-facing ghosts across skill buckets.
//! 2. **The champion generator's parametric-wheel methodology**
//!    (`crates/validator/src/champion.rs` documents the reference champion as
//!    "generated by ML-driven tuning (CMA-ES) over parametric wheel shapes").
//!    We synthesize the same parametric wheel family (circles, ovals, regular
//!    polygons, stars) the champion search explores.
//!
//! Crucially, the seed blobs carry *hand-picked* `finish_time_ms` constants
//! (e.g. 25_400). This binary **ignores those constants** and instead runs
//! every wheel through the actual physics engine (`ResimEngine::resim`, the
//! same WASM the validator uses) to produce a *physics-derived*
//! `finish_time_ms`. Each ghost's finish time is the real re-sim result, not
//! a hand-picked number — satisfying the acceptance criterion that times be
//! "actually produced by the physics engine (not a hand-picked constant)".
//!
//! Every ghost is then encoded into the DRGH binary blob format and decoded
//! back through `drawrace_api::blob::{BlobHeader, GhostBlob}` — exercising the
//! exact decoder the task names — before being emitted as a `ReferenceGhost`.
//!
//! # Output
//!
//! Writes `crates/validator/reference-ghosts.generated.json` (a staged file —
//! this binary does NOT touch `reference-ghosts.json` or `tests/replay.rs`;
//! folding the generated set into the live test is the next child's job).
//!
//! # Usage
//!
//! ```bash
//! cargo run -p drawrace-validator --bin generate-reference-ghosts
//! ```
//!
//! Re-runs are deterministic (seeded LCG, fixed resim seed=42), so the output
//! is regenerable from source.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use chrono::Utc;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use drawrace_api::blob::{BlobHeader, GhostBlob, WheelEntry};
use drawrace_validator::resim::ResimEngine;
use drawrace_validator::track::TrackStore;

/// Physics version to stamp into each ghost's blob + `physics_version` field.
///
/// We deliberately read this from the **loaded** resim WASM at runtime (see
/// `main`) rather than hardcoding the `PHYSICS_VERSION` constant from
/// `packages/engine-core/src/version.ts`. The recorded version must reflect
/// the physics that *actually produced* each finish time — which is whatever
/// the deployed WASM runs. (As of this commit the committed
/// `packages/engine-core/dist/resim.wasm` reports v4 while the TS source
/// declares v8; the artifact is stale. Recording the WASM's true reported
/// version keeps the corpus honest. Re-running this generator after the WASM
/// is rebuilt regenerates the set at the new version.)
/// Fixed re-sim seed — the same seed `tests/replay.rs` uses, so the generated
/// times are exactly what the Layer 6 gate will recompute.
const RESIM_SEED: u32 = 42;
/// Generous claimed-finish bound passed to resim so the physics engine (not an
/// artificial timeout) decides whether a wheel finishes. resim clamps the
/// internal max_ticks to `>= 90*60` regardless.
const CLAIMED_FINISH_TICKS: u32 = 5400; // 90 s @ 60 Hz
/// Target number of finishing ghosts per track (drives the `>=200` gate).
const TARGET_PER_TRACK: usize = 75;
/// Hard cap per track (stops scanning once reached).
const CAP_PER_TRACK: usize = 80;
const DRGH_HEADER_SIZE: usize = 36;

/// Ticks → milliseconds (1 tick = 1/60 s). Integer math keeps the value
/// bit-stable across runs; `tests/replay.rs` inverts this as `ms*60/1000`,
/// which round-trips within the 2-tick replay tolerance.
fn ticks_to_ms(ticks: u32) -> u32 {
    ticks.saturating_mul(1000) / 60
}

// ──────────────────────────────────────────────────────────────────────────
// Output schema — mirrors ReferenceGhost in crates/validator/tests/replay.rs
// ──────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize, Deserialize)]
struct WheelData {
    swap_tick: u32,
    vertex_count: u8,
    polygon_vertices: Vec<(i16, i16)>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct ReferenceGhost {
    ghost_id: String,
    track_id: u16,
    finish_time_ms: u32,
    wheels: Vec<WheelData>,
    physics_version: u32,
    notes: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct ReferenceGhosts {
    version: u32,
    updated_at: String,
    ghosts: HashMap<String, ReferenceGhost>,
}

// ──────────────────────────────────────────────────────────────────────────
// Candidate wheel shapes — sourced from the seed pool + champion parametric
// family. Every candidate is a *drivable* wheel: a closed polygon whose
// vertex count is within the blob's [8,32] cap and whose vertices sit well
// inside the i16 / canvas bounds.
// ──────────────────────────────────────────────────────────────────────────

/// A candidate drivable wheel shape with provenance.
struct Candidate {
    /// Human-readable provenance for the `notes` field.
    source: String,
    vertices: Vec<(f64, f64)>,
}

/// Read the committed seed-ghost pool (`seeds/track_N/*.blob`) and lift each
/// blob's initial wheel (`wheels[0]`) into a candidate shape.
///
/// These blobs are the *output* of `generate-seed-ghosts*` — i.e. produced by
/// the existing seed-ghost generator. We deliberately ignore the blob's
/// hand-picked `finish_time_ms`; only the *shape* is reused. The finish time
/// is recomputed from physics below.
fn seed_candidates(workspace_root: &Path) -> Vec<Candidate> {
    let mut out = Vec::new();
    for track_id in 1u16..=3 {
        let dir = workspace_root
            .join("seeds")
            .join(format!("track_{}", track_id));
        let Ok(entries) = std::fs::read_dir(&dir) else {
            println!("  (no seed dir at {} — skipping seed source)", dir.display());
            continue;
        };
        let mut files: Vec<PathBuf> = entries
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("blob"))
            .collect();
        files.sort();
        for f in files {
            let bytes = match std::fs::read(&f) {
                Ok(b) => b,
                Err(_) => continue,
            };
            // Decode through the named decoder to confirm the seed pool round-trips.
            let blob = match GhostBlob::parse(&bytes) {
                Ok(b) => b,
                Err(e) => {
                    println!("  (skip {}: parse error: {})", f.display(), e);
                    continue;
                }
            };
            let wheel = match blob.wheels.first() {
                Some(w) => w,
                None => continue,
            };
            // Convert i16 1/100-px units back to normalized f64 for the
            // shared parametric pipeline (which re-scales/translates).
            let verts: Vec<(f64, f64)> = wheel
                .polygon_vertices
                .iter()
                .map(|&(x, y)| (x as f64 / 100.0, y as f64 / 100.0))
                .collect();
            let rel = f
                .strip_prefix(workspace_root)
                .unwrap_or(&f)
                .display()
                .to_string();
            out.push(Candidate {
                source: format!("seed blob {} (track {} seed shape)", rel, track_id),
                vertices: verts,
            });
        }
    }
    out
}

/// Deterministic LCG for reproducible parametric perturbation (no `rand`
/// dependency; re-runs are bit-identical).
struct Lcg(u64);
impl Lcg {
    fn new(seed: u64) -> Self {
        Self(seed.wrapping_add(0x9e37_79b9_7f4a_7c15))
    }
    fn next_u32(&mut self) -> u32 {
        // Numerical Recipes LCG constants.
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        ((self.0 >> 32) & 0xffff_ffff) as u32
    }
    /// float in [0,1)
    fn next_f64(&mut self) -> f64 {
        self.next_u32() as f64 / (u32::MAX as f64 + 1.0)
    }
}

/// Generate the parametric wheel family the champion search explores
/// (champion.rs: "parametric wheel shapes"). All outputs are closed polygons
/// with 8..=32 vertices, centroid-translated to the origin.
fn parametric_candidates() -> Vec<Candidate> {
    let mut out = Vec::new();
    // Fixed seed → re-runs are bit-identical (regenerable from source).
    let mut rng = Lcg::new(0xc1a0_5eed_bad_1dea);

    // Regular circles — the baseline drivable shape. Vary radius + resolution.
    for &r in &[40.0_f64, 45.0, 50.0, 55.0, 60.0, 65.0, 70.0, 75.0, 80.0] {
        for &n in &[8usize, 10, 12, 14, 16, 18, 20, 24, 28, 32] {
            out.push(Candidate {
                source: format!("parametric circle r={} n={}", r as i32, n),
                vertices: regular_polygon(n, r, r, 0.0),
            });
        }
    }

    // Ovals — eccentricity changes rolling resistance & moment of inertia.
    for &(a, b) in &[(50.0_f64, 30.0), (60.0, 35.0), (70.0, 40.0), (55.0, 45.0)] {
        for &n in &[12usize, 16, 20, 24] {
            out.push(Candidate {
                source: format!("parametric oval a={} b={} n={}", a as i32, b as i32, n),
                vertices: regular_polygon(n, a, b, 0.0),
            });
        }
    }

    // Rounded stars — angular shapes that "claw" on icy/snowy zones (the
    // gameplay-optimal family for zone B of hills-01 per plan.md §Gameplay 5).
    for &outer in &[50.0_f64, 60.0, 70.0] {
        for &ratio in &[0.40, 0.50, 0.60] {
            for &points in &[4usize, 5, 6, 7] {
                out.push(Candidate {
                    source: format!(
                        "parametric star {}pt outer={} ratio={:.2}",
                        points, outer as i32, ratio
                    ),
                    vertices: star(points, outer, outer * ratio),
                });
            }
        }
    }

    // Rotated + perturbed circles — adds vertex-ordering / winding coverage
    // for the re-sim without leaving the drivable family.
    for i in 0..40 {
        let r = 50.0 + (rng.next_f64() * 30.0); // r in [50, 80)
        let n = 8 + (rng.next_u32() % 25) as usize; // n in [8, 32]
        let rot = rng.next_f64() * std::f64::consts::TAU;
        let mut verts = regular_polygon(n, r, r, rot);
        // Small deterministic radial jitter (±2% of radius) — stays drivable.
        let amp = r * 0.02;
        for v in &mut verts {
            let (x, y) = *v;
            let mag = (x * x + y * y).sqrt().max(1e-9);
            let j = (rng.next_f64() - 0.5) * 2.0 * amp;
            *v = (x + x / mag * j, y + y / mag * j);
        }
        out.push(Candidate {
            source: format!("parametric jittered circle #{} r={:.0} n={}", i, r, n),
            vertices: verts,
        });
    }

    out
}

/// A regular (possibly eccentric) polygon centered at the origin.
fn regular_polygon(n: usize, rx: f64, ry: f64, rotation: f64) -> Vec<(f64, f64)> {
    (0..n)
        .map(|i| {
            let ang = rotation + (i as f64 / n as f64) * std::f64::consts::TAU;
            (ang.cos() * rx, ang.sin() * ry)
        })
        .collect()
}

/// A `points`-pointed star: alternating outer/inner radii. Vertex count =
/// 2*points, kept within [8,32] by the caller's `points` range.
fn star(points: usize, outer: f64, inner: f64) -> Vec<(f64, f64)> {
    let total = points * 2;
    (0..total)
        .map(|i| {
            let ang = (i as f64 / total as f64) * std::f64::consts::TAU - std::f64::consts::FRAC_PI_2;
            let r = if i % 2 == 0 { outer } else { inner };
            (ang.cos() * r, ang.sin() * r)
        })
        .collect()
}

/// Translate a polygon so its area-centroid sits at the origin (mirrors the
/// client draw pipeline, plan.md §Gameplay 2 "Centroid & axle placement").
fn center_on_centroid(verts: &[(f64, f64)]) -> Vec<(f64, f64)> {
    let n = verts.len();
    if n < 3 {
        return verts.to_vec();
    }
    let mut area = 0.0;
    let mut cx = 0.0;
    let mut cy = 0.0;
    for i in 0..n {
        let (x0, y0) = verts[i];
        let (x1, y1) = verts[(i + 1) % n];
        let cross = x0 * y1 - x1 * y0;
        area += cross;
        cx += (x0 + x1) * cross;
        cy += (y0 + y1) * cross;
    }
    if area.abs() < 1e-12 {
        return verts.to_vec();
    }
    let inv = 1.0 / (3.0 * area);
    cx *= inv;
    cy *= inv;
    verts.iter().map(|&(x, y)| (x - cx, y - cy)).collect()
}

/// Convert normalized f64 vertices → i16 1/100-px units (the blob wire format),
/// enforcing the [8,32] vertex cap. Returns None if degenerate.
fn to_wheel_entry(verts: &[(f64, f64)]) -> Option<WheelEntry> {
    if !(8..=32).contains(&verts.len()) {
        return None;
    }
    let polygon_vertices: Vec<(i16, i16)> = verts
        .iter()
        .map(|&(x, y)| {
            let ix = (x * 100.0).round().clamp(-32768.0, 32767.0) as i16;
            let iy = (y * 100.0).round().clamp(-32768.0, 32767.0) as i16;
            (ix, iy)
        })
        .collect();
    // Reject zero-area / degenerate shapes.
    if polygon_vertices
        .iter()
        .zip(polygon_vertices.iter().skip(1))
        .all(|(a, b)| a == b)
    {
        return None;
    }
    Some(WheelEntry {
        swap_tick: 0,
        vertex_count: polygon_vertices.len() as u8,
        polygon_vertices,
    })
}

/// Encode a ghost into the DRGH binary blob format (mirrors the seed
/// generator's layout and the wire spec in `blob.rs` / plan.md §Multiplayer 5).
fn encode_blob(
    physics_version: u8,
    track_id: u16,
    finish_time_ms: u32,
    wheel: &WheelEntry,
) -> Vec<u8> {
    let vc = wheel.vertex_count as usize;
    // Minimal cosmetic stroke (delta-encoded, traces the polygon outline) —
    // required by the format but irrelevant to re-sim.
    let stroke: Vec<(i16, i16, u16)> = wheel
        .polygon_vertices
        .iter()
        .scan((0i16, 0i16), |prev, &(x, y)| {
            let dx = x.wrapping_sub(prev.0);
            let dy = y.wrapping_sub(prev.1);
            *prev = (x, y);
            Some((dx, dy, 16u16))
        })
        .collect();

    let total = DRGH_HEADER_SIZE
        + 1 // wheel_count
        + (4 + 1 + vc * 4) // swap_tick + vertex_count + vertices
        + 1 // point_count
        + stroke.len() * 6
        + 1 // checkpoint_count
        + 0; // no checkpoints

    let mut buf = vec![0u8; total];
    buf[0..4].copy_from_slice(b"DRGH");
    buf[4] = physics_version;
    buf[5..7].copy_from_slice(&track_id.to_le_bytes());
    buf[7] = 0; // flags
    buf[8..12].copy_from_slice(&finish_time_ms.to_le_bytes());
    buf[12..20].copy_from_slice(&0i64.to_le_bytes()); // submitted_at (irrelevant for fixtures)
    let uuid = Uuid::nil();
    buf[20..36].copy_from_slice(uuid.as_bytes());

    let mut o = DRGH_HEADER_SIZE;
    buf[o] = 1; // wheel_count
    o += 1;
    buf[o..o + 4].copy_from_slice(&0u32.to_le_bytes()); // swap_tick = 0
    o += 4;
    buf[o] = wheel.vertex_count;
    o += 1;
    for &(x, y) in &wheel.polygon_vertices {
        buf[o..o + 2].copy_from_slice(&x.to_le_bytes());
        buf[o + 2..o + 4].copy_from_slice(&y.to_le_bytes());
        o += 4;
    }
    buf[o] = stroke.len() as u8;
    o += 1;
    for &(dx, dy, dt) in &stroke {
        buf[o..o + 2].copy_from_slice(&dx.to_le_bytes());
        buf[o + 2..o + 4].copy_from_slice(&dy.to_le_bytes());
        buf[o + 4..o + 6].copy_from_slice(&dt.to_le_bytes());
        o += 6;
    }
    buf[o] = 0; // checkpoint_count
    buf
}

/// Resolve the workspace root from CARGO_MANIFEST_DIR
/// (crates/validator → workspace root).
fn workspace_root() -> Result<PathBuf> {
    let manifest_dir =
        std::env::var("CARGO_MANIFEST_DIR").context("CARGO_MANIFEST_DIR not set")?;
    Ok(PathBuf::from(manifest_dir)
        .parent() // crates
        .and_then(|p| p.parent()) // workspace root
        .map(PathBuf::from)
        .context("could not resolve workspace root")?)
}

fn main() -> Result<()> {
    println!("generate-reference-ghosts: sourcing real drivable ghosts from seed + champion generators\n");

    let ws = workspace_root()?;
    let tracks_dir = ws.join("apps/web/public/tracks");

    // Load the physics engine + the three real tracks.
    println!("Loading resim WASM engine...");
    let engine = ResimEngine::load().context("failed to load resim engine")?;
    let physics_version = engine.physics_version as u8;
    println!("  physics_version = {} (recorded into every ghost)", physics_version);

    println!("Loading tracks from {}...", tracks_dir.display());
    let store = TrackStore::load(tracks_dir.clone()).context("failed to load track store")?;
    let track_ids: Vec<u16> = store.track_ids();
    println!("  tracks: {:?}", track_ids);
    for &tid in &track_ids {
        let td = store.get(tid).unwrap();
        println!(
            "    track {}: finish_x={}, start=({},{}), {} terrain pts, {} obstacles",
            tid, td.finish_x, td.start_x, td.start_y, td.terrain.len(), td.obstacles.len()
        );
    }

    // Gather candidate shapes: seed pool (primary) + parametric family (champion methodology).
    println!("\nGathering candidate wheel shapes...");
    let mut candidates = seed_candidates(&ws);
    let seed_count = candidates.len();
    candidates.extend(parametric_candidates());
    println!(
        "  {} seed-sourced + {} parametric = {} total candidates",
        seed_count,
        candidates.len() - seed_count,
        candidates.len()
    );

    // Center every candidate on its centroid (matches the client pipeline).
    for c in &mut candidates {
        c.vertices = center_on_centroid(&c.vertices);
    }

    // Re-simulate each candidate on each track; keep physics-derived finishes.
    let mut per_track: HashMap<u16, Vec<ReferenceGhost>> = HashMap::new();
    let mut scanned = 0usize;
    let mut dnf = 0usize;
    let mut malformed = 0usize;

    'outer: for cand in &candidates {
        let wheel = match to_wheel_entry(&cand.vertices) {
            Some(w) => w,
            None => {
                malformed += 1;
                continue;
            }
        };
        for &tid in &track_ids {
            // Stop once every track is at its cap. Iterate over `track_ids`
            // (not `per_track.values()`): `Iterator::all` is vacuously `true`
            // on an empty iterator, so the `.values()` form would abort the
            // whole scan before a single track is populated.
            if track_ids
                .iter()
                .all(|&t| per_track.get(&t).map_or(0, |v| v.len()) >= CAP_PER_TRACK)
            {
                break 'outer;
            }
            // Skip tracks already at cap.
            if per_track.get(&tid).map_or(0, |v| v.len()) >= CAP_PER_TRACK {
                continue;
            }

            scanned += 1;
            let td = store.get(tid).unwrap();
            let resim_wheels = vec![wheel.clone()];
            let result = match engine.resim(
                &resim_wheels,
                &td.terrain,
                &td.obstacles,
                td.finish_x,
                td.start_x,
                td.start_y,
                CLAIMED_FINISH_TICKS,
                RESIM_SEED,
            ) {
                Ok(r) => r,
                Err(e) => {
                    println!("  (resim error on {}: {})", cand.source, e);
                    dnf += 1;
                    continue;
                }
            };
            let finish_ticks = match result.finish_ticks {
                Some(t) => t,
                None => {
                    dnf += 1;
                    continue; // wheel did not finish on this track — not drivable here
                }
            };
            let finish_time_ms = ticks_to_ms(finish_ticks);

            // Encode → decode round-trip through the named blob decoder.
            let blob_bytes = encode_blob(physics_version, tid, finish_time_ms, &wheel);
            let parsed = GhostBlob::parse(&blob_bytes)
                .with_context(|| format!("self-encoded blob failed to parse: {}", cand.source))?;
            // Sanity: the decoded header carries our physics-derived time + version.
            let header = BlobHeader::parse(&blob_bytes)?;
            assert_eq!(
                header.finish_time_ms, finish_time_ms,
                "decoded finish_time_ms must match the physics-derived value"
            );
            assert_eq!(header.version, physics_version);

            let parsed_wheel = &parsed.wheels[0];
            let bucket = per_track.entry(tid).or_default();
            let idx = bucket.len();
            let prefix = if cand.source.starts_with("seed blob") {
                "seed"
            } else {
                "param"
            };
            let ghost_id = format!("{}-t{}-{:03}", prefix, tid, idx);
            let ghost = ReferenceGhost {
                ghost_id: ghost_id.clone(),
                track_id: tid,
                finish_time_ms,
                wheels: vec![WheelData {
                    swap_tick: parsed_wheel.swap_tick,
                    vertex_count: parsed_wheel.vertex_count,
                    polygon_vertices: parsed_wheel.polygon_vertices.clone(),
                }],
                physics_version: physics_version as u32,
                notes: format!(
                    "{}; finish_time_ms={} ({} ticks) derived by ResimEngine resim seed={}",
                    cand.source, finish_time_ms, finish_ticks, RESIM_SEED
                ),
            };
            bucket.push(ghost);
        }
    }

    // Flatten, ordered by track then index.
    let mut all_ghosts: Vec<ReferenceGhost> = Vec::new();
    let mut counts: HashMap<u16, usize> = HashMap::new();
    for tid in [1u16, 2, 3] {
        let bucket = per_track.remove(&tid).unwrap_or_default();
        counts.insert(tid, bucket.len());
        all_ghosts.extend(bucket);
    }
    all_ghosts.sort_by(|a, b| {
        (
            a.track_id,
            a.ghost_id.starts_with("seed") as u8,
            &a.ghost_id,
        )
            .cmp(&(
                b.track_id,
                b.ghost_id.starts_with("seed") as u8,
                &b.ghost_id,
            ))
    });

    let total = all_ghosts.len();
    println!("\n=== Generation summary ===");
    println!("candidates scanned (shape×track): {}", scanned);
    println!("DNF / not-finishing: {}", dnf);
    println!("malformed (skipped): {}", malformed);
    println!("ghosts generated:   {}", total);
    println!("per-track: {}", {
        let mut s = String::new();
        for tid in [1u16, 2, 3] {
            s.push_str(&format!("t{}={} ", tid, counts.get(&tid).copied().unwrap_or(0)));
        }
        s
    });
    let seed_n = all_ghosts.iter().filter(|g| g.ghost_id.starts_with("seed")).count();
    let param_n = total - seed_n;
    println!("source mix: {} seed-sourced, {} parametric-sourced", seed_n, param_n);

    // Finish-time distribution (proves times are physics-spread, not a constant).
    if total > 0 {
        let mut times: Vec<u32> = all_ghosts.iter().map(|g| g.finish_time_ms).collect();
        times.sort_unstable();
        let min = times.first().copied().unwrap();
        let max = times.last().copied().unwrap();
        let distinct = {
            let mut d = times.clone();
            d.dedup();
            d.len()
        };
        println!(
            "finish_time_ms range: {}..{} ms, {} distinct values (proves physics-derived, not a constant)",
            min, max, distinct
        );
    }

    if total < 200 || counts.values().any(|&c| c == 0) {
        anyhow::bail!(
            "FAILED acceptance gate: need >=200 ghosts spanning tracks 1,2,3; got {} ({:?})",
            total, counts
        );
    }

    // Emit staged JSON (NOT reference-ghosts.json — folding in is the next child).
    let ghosts_map: HashMap<String, ReferenceGhost> = all_ghosts
        .iter()
        .map(|g| (g.ghost_id.clone(), g.clone()))
        .collect();
    let out = ReferenceGhosts {
        version: 1,
        updated_at: Utc::now().to_rfc3339(),
        ghosts: ghosts_map,
    };
    let json = serde_json::to_string_pretty(&out)?;
    let out_path = ws.join("crates/validator/reference-ghosts.generated.json");
    std::fs::write(&out_path, json)?;
    println!("\nWrote {} ghosts to {}", total, out_path.display());
    println!("Zero synth-track-* keys: {}",
        all_ghosts.iter().all(|g| !g.ghost_id.contains("synth-track")));
    println!("\nNext step (separate child): fold this file into crates/validator/reference-ghosts.json.");

    Ok(())
}
